            "   Instead of sequential recurrent gates (RNN/BiLSTM), Multi-Head Self-Attention projects queries/keys/values across $h=4$ heads:\n",
            "   - **Head 1 (Injection Edge):** Captures $E_{\\text{incoming}} \\leftrightarrow E_{\\text{current}}$ (Did an external thread cause this child action?).\n",
            "   - **Head 2 (Lineage Edge):** Captures $E_{\\text{parent}} \\leftrightarrow E_{\\text{current}}$ (Is the child action consistent with parent role?).\n",
            "   - **Head 3 (Tampering Edge):** Captures $E_{\\text{incoming}} \\leftrightarrow E_{\\text{parent}}$ (Was the parent process itself tampered with?).\n",
            "   - **Head 4 (Synthesis Edge):** Fuses the complete 2-hop causal provenance context.\n",
            "3. **Incremental Learning (IL) Expandable Adapter:**\n",
            "   When adapting across domains (SC1 -> SC2 -> SC3), the base Transformer is frozen, and a lightweight **Residual Bottleneck Adapter** is trained to eliminate **Catastrophic Forgetting**.\n",
            "4. **Dual GPU T4x2 Acceleration:** Scales training across both Tesla T4 GPUs using PyTorch DistributedDataParallel (DDP) with NCCL backend."
